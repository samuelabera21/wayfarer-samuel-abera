BEGIN;

-- Track database migrations that have been successfully applied.
CREATE TABLE schema_migrations (
    version VARCHAR(100) PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- Store the predefined travellers who can act in the application.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT chk_users_name_not_empty
        CHECK (BTRIM(name) <> '')
);

-- Store tourist destinations available in Wayfarer.
CREATE TABLE places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(50) NOT NULL,
    description TEXT NOT NULL,
    opening_hours TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_places PRIMARY KEY (id),
    CONSTRAINT chk_places_name_not_empty
        CHECK (BTRIM(name) <> ''),
    CONSTRAINT chk_places_category_not_empty
        CHECK (BTRIM(category) <> ''),
    CONSTRAINT chk_places_description_not_empty
        CHECK (BTRIM(description) <> '')
);


-- Store traveller reviews for places.
CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    place_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    rating SMALLINT NOT NULL,
    body VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_reviews PRIMARY KEY (id),

    CONSTRAINT fk_reviews_place
        FOREIGN KEY (place_id)
        REFERENCES places (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_reviews_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_reviews_place_user
        UNIQUE (place_id, user_id),

    CONSTRAINT chk_reviews_rating
        CHECK (rating BETWEEN 1 AND 5),

    CONSTRAINT chk_reviews_body_not_empty
        CHECK (BTRIM(body) <> '')
);


-- Store scheduled guided tours for each tourist destination.
CREATE TABLE tour_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    place_id BIGINT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    capacity INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_tour_slots PRIMARY KEY (id),

    CONSTRAINT fk_tour_slots_place
        FOREIGN KEY (place_id)
        REFERENCES places (id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_tour_slots_capacity
        CHECK (capacity > 0)
);


-- Store traveller reservations for guided tour slots.
CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slot_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    seats INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_bookings PRIMARY KEY (id),

    CONSTRAINT fk_bookings_slot
        FOREIGN KEY (slot_id)
        REFERENCES tour_slots (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_bookings_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_bookings_slot_user
        UNIQUE (slot_id, user_id),

    CONSTRAINT chk_bookings_seats
        CHECK (seats > 0)
);

-- Index places by category for backend filtering.
CREATE INDEX idx_places_category
    ON places (category);

-- Index reviews by user for user-related queries.
CREATE INDEX idx_reviews_user_id
    ON reviews (user_id);

-- Retrieve a place's tour slots in chronological order.
CREATE INDEX idx_tour_slots_place_starts_at
    ON tour_slots (place_id, starts_at);

-- Retrieve bookings belonging to a particular user.
CREATE INDEX idx_bookings_user_id
    ON bookings (user_id);

-- Record the successfully applied initial schema migration.
INSERT INTO schema_migrations (version)
VALUES ('001_initial_schema');

-- Commit the complete schema migration.
COMMIT;
